"""Export the exact instructions of every design into paper/sections/appendix_prompts.tex."""
import sys
from pathlib import Path
HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "harness"))
import tenancy_methods as tm
import theft_methods as th
from theft_data import UNRESOLVED

def verb(title, text):
    return ("\\paragraph{" + title + "}\n\\begin{lstlisting}\n" + text.strip() + "\n\\end{lstlisting}\n")

out = ["% Generated by analysis/export_prompts.py from the harness code. Do not edit.",
       "\\subsection{Instructions given to each design}", "\\label{app:prompts}",
       "Every design receives the claim sources in the user message as JSON. For tenancy, the system message contains the "
       "shared case-reading policy, the admitted rule packs (process catalogues without assertion strings, the condition "
       "catalogue, the operational routing questions and the required facts per document type) and the design's task; for "
       "theft it contains the policy, the 197 source passages, the catalogue of 33 document types and, for Rules in context, "
       "the extracted rules. All outputs are constrained by strict JSON schemas, released with the code.",
       verb("Shared case-reading policy (tenancy)", tm.POLICY),
       verb("Rules in context (tenancy)", tm.B1_TASK),
       verb("Model executes rules (tenancy)", tm.B2_TASK),
       verb("CasePath interpretation (tenancy, product instructions restricted to conditions and documents)", tm.CP_INTERPRET_TASK),
       verb("CasePath verification (tenancy)", tm.CP_VERIFY_TASK),
       verb("Shared policy (theft)", th.POLICY),
       verb("Direct and Rules in context (theft)", th.PLAN_TASK),
       verb("CasePath interpretation (theft; followed by the 87 conditions)", th.CP_TASK.removesuffix("Conditions:\n").rstrip()),
       verb("CasePath verification (theft)", th.VERIFY_TASK.removesuffix("Conditions:\n").rstrip()),
       "\\subsection{Unresolved-fact sentences}\n\\label{app:unresolved}\nEach sentence replaces the condition's negative statement in the off case of every story.\n\\begin{description}[leftmargin=1em,style=nextline]"]
for cond, sent in UNRESOLVED.items():
    out.append("\\item[" + cond.replace("PR_", "").replace("_", " ") + "] " + sent)
out.append("\\end{description}")
(HERE.parent / "paper" / "sections" / "appendix_prompts.tex").write_text("\n".join(out) + "\n")
print("written")
