"""Write paper/results/numbers_baseline_check.tex: the numbers of the fair-baseline check (Study 4, step 1) as LaTeX
macros. No model calls. POST HOC, on Study 3's data: the paper must label them "added after the test".

    python3 make_numbers_baseline_check.py

Source, read only: study4/baseline_check/REPORT.json (written by study4/baseline_check/analyse.py). All macros start with
\\sbc. A missing key raises an error; nothing is filled in. Never edit the output by hand.

Names: \\sbc<Design><Subset><Measure> for the per-design values (claim-run means for tenancy, pair or pair-run shares for
theft), \\sbcC<A>Vs<B><Subset><Measure><Diff|PCases|PClusters|AHigher|ALower> for the tenancy contrasts and
\\sbcCTh<A>Vs<B><Measure><...> for the theft contrasts (A minus B; p over cases and over the registered clusters).
"""
from __future__ import annotations

import json
import re
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

HERE = Path(__file__).resolve().parent
TMIS = HERE.parent
SRC = TMIS / "study4" / "baseline_check" / "REPORT.json"
OUT = TMIS / "paper" / "results" / "numbers_baseline_check.tex"

DESIGNS = {"casepath": "CasePath", "casepath_checklist": "Checklist", "casepath_frontier_checklist": "FrontierChecklist",
           "hold_prompt": "HoldPrompt", "hold_prompt_frontier": "HoldPromptFrontier", "mer_hold_frontier": "MerHoldFrontier",
           "ric": "Ric", "ric_frontier": "RicFrontier", "model_executes_rules": "Mer", "react": "React",
           "self_consistency": "SelfCons"}
SUBSETS = {"all": "All", "S": "S", "O": "O", "O: open branch fact only": "OpenBranch", "O: denied defining event": "ODenied",
           "O: open defining event": "OOpenEvent", "denied_event": "Denied", "open_event": "OpenEvent", "ordinary": "Ordinary"}
TEN_MEASURES = {"strict_unsafe": "Strict", "all_dev": "AllDev", "held_req_per_claim": "HeldReq",
                "spurious_hold_per_claim": "SpurHold", "missed_per_claim": "Missed", "unnecessary_per_claim": "Unnec",
                "premature_per_claim": "Premature"}
TH_MEASURES = {"errors_per_pair": ("Errors", "num"), "unchanged_share": ("Unchanged", "pct"),
               "premature_share": ("Premature", "pct"), "held_share": ("OpenHeld", "pct")}
CMEAS = {"strict_unsafe": "Strict", "all_dev": "AllDev", "errors": "Errors", "stable": "Unchanged",
         "premature": "Premature", "held": "OpenHeld"}

lines = [f"% Generated by analysis/make_numbers_baseline_check.py from {SRC.relative_to(TMIS)}. Post hoc (added after "
         "the test, on Study 3's data). Do not edit."]
seen = set()


class Missing(KeyError):
    pass


def get(obj, *path):
    cur = obj
    for i, k in enumerate(path):
        try:
            cur = cur[k]
        except (KeyError, IndexError, TypeError):
            raise Missing(f"missing key {'/'.join(map(str, path[:i + 1]))}") from None
    if cur is None:
        raise Missing(f"value is null at {'/'.join(map(str, path))}")
    return cur


def m(name, value):
    if not re.fullmatch(r"sbc[A-Za-z]+", name):
        raise ValueError(f"bad macro name {name}")
    if name in seen:
        raise ValueError(f"duplicate macro {name}")
    seen.add(name)
    lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")


def num(x, nd=2):
    s = str(Decimal(repr(float(x))).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP))
    if re.fullmatch(r"-0\.?0*", s):
        s = s[1:]
    return s.replace("-", "\\ensuremath{-}", 1) if s.startswith("-") else s


def pct(x):
    return num(100 * x, 0) + "\\%"


def p4(x):
    return "< 0.0001" if x < 0.0001 else str(Decimal(repr(float(x))).quantize(Decimal("0.0001"), rounding=ROUND_HALF_UP))


def build(res):
    if "POST HOC" not in get(res, "label"):
        raise ValueError("source is not labelled post hoc")
    for d, dn in DESIGNS.items():
        for sub, sn in SUBSETS.items():
            row = get(res, "tenancy", d, sub)
            for k, kn in TEN_MEASURES.items():
                m(f"sbc{dn}{sn}{kn}", num(get(row, k)))
            m(f"sbc{dn}{sn}Claims", get(row, "claims"))
        row = get(res, "theft", d)
        for k, (kn, kind) in TH_MEASURES.items():
            m(f"sbc{dn}Th{kn}", num(get(row, k)) if kind == "num" else pct(get(row, k)))
    for c in get(res, "contrasts", "tenancy"):
        pre = f"sbcC{DESIGNS[c['a']]}Vs{DESIGNS[c['b']]}{SUBSETS[c['subset']]}{CMEAS[c['measure']]}"
        m(pre + "Diff", num(get(c, "diff_case_mean")))
        m(pre + "PCases", p4(get(c, "p_cases")))
        m(pre + "PClusters", p4(get(c, "p_clusters")))
        m(pre + "ALower", get(c, "a_lower_cases"))
        m(pre + "AHigher", get(c, "a_higher_cases"))
    for c in get(res, "contrasts", "theft"):
        pre = f"sbcCTh{DESIGNS[c['a']]}Vs{DESIGNS[c['b']]}{CMEAS[c['measure']]}"
        m(pre + "Diff", num(get(c, "diff_case_mean")))
        m(pre + "PCases", p4(get(c, "p_cases")))
        m(pre + "PClusters", p4(get(c, "p_clusters")))
    fo = get(res, "failed_outputs")
    m("sbcOutputs", sum(get(v, "entries") for v in fo.values()))
    m("sbcFailedOutputs", sum(len(get(v, "failed")) for v in fo.values()))
    return lines


if __name__ == "__main__":
    build(json.loads(SRC.read_text()))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {len(lines) - 1} macros to {OUT}")
