class Missing(KeyError):
    pass


def get(obj, *path):
    """obj[path[0]][path[1]]...; raises with the full path when a key is missing or the value is None."""
    cur = obj
    for i, k in enumerate(path):
        try:
            cur = cur[k]
        except (KeyError, IndexError, TypeError):
            raise Missing(f"missing key {'/'.join(map(str, path[:i + 1]))}") from None
    if cur is None:
        raise Missing(f"value is null at {'/'.join(map(str, path))}")
    return cur


def m(name, value):
    if not re.fullmatch(r"sthree[A-Za-z]+", name):
        raise ValueError(f"bad macro name {name}")
    if name in seen:
        raise ValueError(f"duplicate macro {name}")
    seen.add(name)
    lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")


def neg(s):
    return s.replace("-", "\\ensuremath{-}", 1) if s.startswith("-") else s


def rnd(x, nd):
    """Round half away from zero (as written by hand: -1.125 -> -1.13), not Python's half to even."""
    q = Decimal(1).scaleb(-nd)
    s = str(Decimal(repr(float(x))).quantize(q, rounding=ROUND_HALF_UP))
    return "0." + "0" * nd if s.lstrip("-") == "0." + "0" * nd else s


def f2(x):
    return neg(rnd(x, 2))


def pct(x):
    return rnd(100 * x, 0)


def usd(x, nd=3):
    return rnd(x, nd)


def pfmt(p):
    """p for the text: < 0.0001 as such; below 0.001 one significant digit; below 0.01 two; else three."""
    if p < 0.0001:
        return "0.0001", "<"
    if p < 0.001:
        return f"{p:.1g}", "="
    if p < 0.01:
        return f"{p:.2g}", "="
    return f"{float(f'{p:.3g}'):g}", "="


def contrast_macros(prefix, c):
    try:
        _contrast_macros(prefix, c)
    except Missing as e:
        raise Missing(f"{prefix}: {e.args[0]}") from None


def _contrast_macros(prefix, c):
    m(prefix + "A", f2(get(c, "a_value")))
    m(prefix + "B", f2(get(c, "b_value")))
    m(prefix + "Diff", f2(get(c, "diff")))
    m(prefix + "Lo", f2(get(c, "diff_ci", 0)))
    m(prefix + "Hi", f2(get(c, "diff_ci", 1)))
    p, rel = pfmt(get(c, "p"))
    m(prefix + "P", p)
    m(prefix + "Peq", f"{rel} {p}")
    m(prefix + "PCell", p if rel == "=" else f"\\ensuremath{{<}}\\,{p}")
    m(prefix + "MinP", pfmt(get(c, "min_p"))[0])
    m(prefix + "Clusters", get(c, "clusters"))
    m(prefix + "Nonzero", get(c, "nonzero_clusters"))


