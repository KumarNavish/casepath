"""Write paper/results/numbers_study3_feedback.tex: the numbers of the analyses asked for by outside feedback (F1-F5),
as LaTeX macros. No model calls. POST HOC: the paper must label them so.

    python3 make_numbers_study3_feedback.py

Source, read only: analysis/study3_feedback.json and the test count of test_study3_feedback.py. All macros start with
\\sthreeF. A missing key raises an error; nothing is filled in. Never edit the output by hand.
"""
from __future__ import annotations

import json
import re
from decimal import ROUND_HALF_UP, Decimal
from pathlib import Path

HERE = Path(__file__).resolve().parent
TMIS = HERE.parent
SRC = HERE / "study3_feedback.json"
OUT = TMIS / "paper" / "results" / "numbers_study3_feedback.tex"

DESIGNS = {"casepath": "CasePath", "casepath_checklist": "Checklist", "casepath_frontier_checklist": "FrontierChecklist",
           "ric": "Ric", "ric_frontier": "RicFrontier", "self_consistency": "SelfCons", "model_executes_rules": "Mer",
           "react": "React", "two_valued_false": "TwoValFalse", "two_valued_true": "TwoValTrue", "core": "Core",
           "ric_original": "RicOrig", "ric_original_frontier": "RicOrigFrontier"}
NUM = {1: "One", 2: "Two", 3: "Three", 5: "Five", 7: "Seven", 9: "Nine", 11: "Eleven", 13: "Thirteen", 15: "Fifteen"}
READINGS = {"reading A1: a denied defining event does not stop the process": "AOne",
            "reading A2: an open defining event is presumed to have occurred": "ATwo",
            "reading A3: optional documents are requested": "AThree",
            "reading A4: a family-home condition excludes arrears": "AFour", "readings A1-A4 together": "AAll",
            "registered reference (check)": "Reg"}
SUBS = {"all claims": "All", "ordinary": "Ordinary", "denied_event": "Denied", "open_event": "OpenEvent"}

lines = [f"% Generated by analysis/make_numbers_study3_feedback.py from {SRC.name}. Post hoc (outside feedback). Do not edit."]
seen = set()


class Missing(KeyError):
    pass


def get(obj, *path):
    cur = obj
    for i, k in enumerate(path):
        try:
            cur = cur[k]
        except (KeyError, IndexError, TypeError):
            raise Missing(f"missing key {'/'.join(map(str, path[:i + 1]))}") from None
    if cur is None:
        raise Missing(f"value is null at {'/'.join(map(str, path))}")
    return cur


def m(name, value):
    if not re.fullmatch(r"sthreeF[A-Za-z]+", name):
        raise ValueError(f"bad macro name {name}")
    if name in seen:
        raise ValueError(f"duplicate macro {name}")
    seen.add(name)
    lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")


def num(x, nd=2):
    s = str(Decimal(repr(float(x))).quantize(Decimal(1).scaleb(-nd), rounding=ROUND_HALF_UP))
    if re.fullmatch(r"-0\.?0*", s):
        s = s[1:]
    return s.replace("-", "\\ensuremath{-}", 1) if s.startswith("-") else s


def pct(x, nd=0):
    return num(100 * x, nd) + "\\%"


def p4(x):
    return "< 0.0001" if x < 0.0001 else str(Decimal(repr(float(x))).quantize(Decimal("0.0001"), rounding=ROUND_HALF_UP))


def contrast(prefix, c):
    m(prefix + "Diff", num(get(c, "diff")))
    m(prefix + "Lo", num(get(c, "diff_ci", 0)))
    m(prefix + "Hi", num(get(c, "diff_ci", 1)))
    m(prefix + "P", p4(get(c, "p")))


res = json.loads(SRC.read_text())
if get(res, "posthoc") is not True or get(res, "preregistered") is not False:
    raise ValueError("source is not labelled post hoc")
m("sthreeFTests", len(re.findall(r"^    def test_", (HERE / "test_study3_feedback.py").read_text(), re.M)))

# F1
t = get(res, "F1", "tenancy")
m("sthreeFOneClaimsS", get(t, "counts", "S"))
m("sthreeFOneClaimsO", get(t, "counts", "O"))
for d, v in get(t, "by_design").items():
    for ty in ("S", "O"):
        pre = f"sthreeFOne{DESIGNS[d]}{ty}"
        m(pre + "Strict", num(get(v, ty, "strict_unsafe_family_mean")))
        m(pre + "StrictClaimRun", num(get(v, ty, "strict_unsafe_claim_run_mean")))
        m(pre + "AllDev", num(get(v, ty, "all_dev_family_mean")))
        m(pre + "Exact", pct(get(v, ty, "exact_share_family_mean")))
for b, v in get(t, "contrasts").items():
    for ty in ("S", "O"):
        contrast(f"sthreeFOneVs{DESIGNS[b]}{ty}Strict", get(v, ty, "strict_unsafe"))
        contrast(f"sthreeFOneVs{DESIGNS[b]}{ty}AllDev", get(v, ty, "all_dev"))
th = get(res, "F1", "theft")
for d, v in get(th, "by_design").items():
    pre = f"sthreeFOneTh{DESIGNS[d]}"
    m(pre + "Errors", num(get(v, "S", "errors_per_pair")))
    m(pre + "Unchanged", pct(get(v, "O", "unchanged_share")))
    m(pre + "Premature", pct(get(v, "O", "premature_share")))
for b, v in get(th, "contrasts").items():
    contrast(f"sthreeFOneThVs{DESIGNS[b]}Unchanged", get(v, "O unchanged share"))

# F2
f2 = get(res, "F2")
m("sthreeFTwoTestShare", pct(get(f2, "q_test")))
for field, fn in (("strict_unsafe", "Strict"), ("all_dev", "AllDev")):
    y = get(f2, "measures", field)
    for k, v in get(y, "crossovers").items():
        a, b = k.split(" vs ")
        if a != "casepath":
            continue
        q = v["claim_run"]
        m(f"sthreeFTwo{fn}CrossCasePath{DESIGNS[b]}", "none in 0--1" if q is None else pct(q))
        qf = v["family"]
        m(f"sthreeFTwo{fn}CrossCasePath{DESIGNS[b]}Family", "none in 0--1" if qf is None else pct(qf, 1))

# F3
f3 = get(res, "F3")
for variant, vn in (("H5 bootstrap p", "Boot"), ("H5 exact sign-flip p", "Exact")):
    proc = get(f3, "procedures", variant)
    for pname, pn in (("frozen order (registered)", "Frozen"), ("final draft before the reorder", "FinalDraft"),
                      ("first draft", "FirstDraft"), ("Holm over the five registered hypotheses", "Holm")):
        for h, st in get(proc, pname).items():
            hn = {"H1": "HOne", "H2": "HTwo", "H3": "HThree", "H4": "HFour", "H5": "HFive", "H3-NI (first draft)": "HThreeNI"}[h]
            status = st[0] if pname.startswith("Holm") else st
            m(f"sthreeFThree{vn}{pn}{hn}", status)
            if pname.startswith("Holm"):
                m(f"sthreeFThree{vn}{pn}{hn}AdjP", p4(st[1]))
h4 = get(f3, "h4_self_consistency")
m("sthreeFThreeSCMinP", p4(get(h4, "smallest_p")))
m("sthreeFThreeSCP", p4(get(h4, "p")))
fd = get(f3, "first_draft_h3_ni")
m("sthreeFThreeFirstDraftNIDiff", num(get(fd, "diff")))
m("sthreeFThreeFirstDraftNIP", p4(get(fd, "p")))

# F4
f4 = get(res, "F4")
for regime, rn in (("tenancy", "Ten"), ("theft", "Th")):
    key = "strict_unsafe_per_claim" if regime == "tenancy" else "errors_per_pair"
    for k, v in get(f4, "readings", regime, "by_k").items():
        pre = f"sthreeFFour{rn}K{NUM[int(k)]}"
        m(pre + "Errors", num(get(v, key)))
        m(pre + "Cost", num(get(v, "cost_per_case_run"), 4))
        if regime == "theft":
            m(pre + "Unchanged", pct(get(v, "unresolved_unchanged_share")))
        else:
            m(pre + "AllDev", num(get(v, "all_deviations_per_claim")))
            m(pre + "SpurHold", num(get(v, "spurious_holds_per_claim"), 3))
            m(pre + "CorrectHold", pct(get(v, "correct_hold_share")))
    for mm, v in get(f4, "self_consistency", regime, "by_m").items():
        pre = f"sthreeFFour{rn}M{NUM[int(mm)]}"
        m(pre + "Errors", num(get(v, key)))
        m(pre + "Cost", num(get(v, "cost_per_case_run"), 4))
    for target, tn in (("checklist only", "Checklist"), ("full product", "Full")):
        v = get(f4, "budget", regime, target)
        if not v["reached"]:
            m(f"sthreeFFour{rn}Budget{tn}", "not reached")
            continue
        m(f"sthreeFFour{rn}Budget{tn}M", get(v, "m"))
        contrast(f"sthreeFFour{rn}Budget{tn}", get(v, "contrast"))
        if "contrast_full_product" in v:
            contrast(f"sthreeFFour{rn}Budget{tn}FullProduct", get(v, "contrast_full_product"))

# F5
f5 = get(res, "F5")
names = {r["name"]: r for r in get(f5, "results")}
for lab, nm in (("clean room: evaluator A", "EvalA"), ("clean room: evaluator B", "EvalB"),
                ("clean room: registered reference as given to the comparison", "Registered")):
    r = get(names, lab)
    m(f"sthreeFFive{nm}Same", get(r, "agreement_by_subset", "all", "same_state"))
    m(f"sthreeFFive{nm}Documents", get(r, "agreement_by_subset", "all", "documents"))
for lab, nm in READINGS.items():
    if lab not in names:
        continue
    r = names[lab]
    m(f"sthreeFFive{nm}Same", get(r, "agreement_by_subset", "all", "same_state"))
    for d in ("casepath", "ric", "ric_frontier", "self_consistency", "model_executes_rules"):
        for sub, sn in SUBS.items():
            m(f"sthreeFFive{nm}{DESIGNS[d]}Strict{sn}", num(get(r, "by_design", d, f"strict_unsafe|{sub}")))
    # The remaining designs of the full reading x design table (supplement), and all deviations over all claims.
    for d in ("casepath_checklist", "casepath_frontier_checklist", "react", "two_valued_false", "two_valued_true"):
        for sub, sn in SUBS.items():
            m(f"sthreeFFive{nm}{DESIGNS[d]}Strict{sn}", num(get(r, "by_design", d, f"strict_unsafe|{sub}")))
    for d in get(r, "by_design"):
        m(f"sthreeFFive{nm}{DESIGNS[d]}AllDevAll", num(get(r, "by_design", d, "all_deviations|all claims")))
    for c in get(r, "contrasts"):
        cid = {"H2": "HTwo", "H3": "HThree", "S2a": "STwoA", "S2b": "STwoB", "S2c": "STwoC", "S2d": "STwoD", "S2e": "STwoE",
               "S2f": "STwoF", "S3a": "SThreeA", "S3b": "SThreeB"}[c["id"]]
        contrast(f"sthreeFFive{nm}{cid}", get(c, "alternative"))
        m(f"sthreeFFive{nm}{cid}Verdict", get(c, "verdict"))

# F5b
RB = {"registered": "Registered", "A1": "AOne", "A2": "ATwo", "A3": "AThree", "A4": "AFour", "all": "AAll"}
for rk, v in get(res, "F5b", "readings").items():
    if "designs" not in v:
        continue
    pre = f"sthreeFFiveB{RB[rk]}"
    for d in ("casepath", "casepath_checklist", "casepath_frontier_checklist"):
        m(f"{pre}{DESIGNS[d]}Strict", num(get(v, "designs", d, "strict_unsafe|all claims")))
        for sub, sn in list(SUBS.items())[1:]:
            m(f"{pre}{DESIGNS[d]}Strict{sn}", num(get(v, "designs", d, f"strict_unsafe|{sub}")))
    m(f"{pre}CasePathStrictUnmatched", num(get(v, "designs", "casepath", "strict_unsafe|all claims, registered workflow (F5)")))
    for b, x in get(v, "baselines").items():
        m(f"{pre}{DESIGNS[b]}Strict", num(get(x, "strict_unsafe|all claims")))
    for cid, c in get(v, "contrasts").items():
        cn = {"H2": "HTwo", "H3": "HThree", "S2a": "STwoA", "S2b": "STwoB", "S2c": "STwoC"}[cid]
        contrast(f"{pre}{cn}", c)
        m(f"{pre}{cn}Verdict", get(c, "verdict"))
for d, cnt in get(res, "F5b", "checks").items():
    if isinstance(cnt, dict):
        m(f"sthreeFFiveBReproduces{DESIGNS[d]}", get(cnt, "replay reproduces the stored scored checklist"))
        m(f"sthreeFFiveBReplayed{DESIGNS[d]}", get(cnt, "replayed"))

OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {len(lines) - 1} macros to {OUT}")
