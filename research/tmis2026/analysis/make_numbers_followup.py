seen = set()


def m(name, value):
    if not re.fullmatch(r"fu[A-Za-z]+", name):
        raise ValueError(f"bad macro name {name}")
    if name in seen:
        raise ValueError(f"duplicate macro {name}")
    seen.add(name)
    lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")


def check(cond, msg):
    if not cond:
        raise AssertionError(msg)


