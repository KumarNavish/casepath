"""Write paper/results/numbers_followup.tex: the numbers of the work done after the confirmatory test (Study 3), as
LaTeX macros with the prefix \\fu. No model calls. None of this work is pre-registered; from the end of the test on, the
theft stories of fresh2/ are development data, and the paper must say so.

    python3 make_numbers_followup.py

Sources, read only (each is the JSON next to the report the paper cites):
- analysis/theft_diagnosis.json      (analysis/theft_diagnosis.md, Parts 1-6)
- analysis/rule_lint.json            (analysis/rule_lint.md)
- rule_review/final/reviewed_rules.json, rule_review/lint/final/reviewed_rules.json and the two editors' changes.json
                                     (rule_review/lint/final/RECONCILIATION.md)
- analysis/rule_lint_eval.json       (analysis/rule_lint_eval.md)
- runs/speed/part_a.json, part_b.json, part_d.json, replay_summary.json
                                     (runs/speed/part_a.md, part_b.md, replay_summary.md)
A missing key raises an error; nothing is filled in. Never edit the output by hand.
"""
