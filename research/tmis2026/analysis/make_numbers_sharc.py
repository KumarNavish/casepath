"""Write paper/results/numbers_sharc.tex from runs/sharc/summary.json (ShARC pilot, train split).
Every ShARC number the paper reports is a macro made here. Never edit the output by hand."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent / "runs" / "sharc" / "summary.json"
OUT = HERE.parent / "paper" / "results" / "numbers_sharc.tex"

s = json.loads(SRC.read_text())
lines = ["% Generated by analysis/make_numbers_sharc.py from runs/sharc/summary.json. Do not edit."]


def m(name, value):
    lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")


NAMES = {"direct": "Direct", "steps": "Steps", "sc3": "SC", "cp_core": "Core", "cp_kleene": "Kleene", "cp_single": "Single"}
m("sharcN", s["n"])
m("sharcClusters", s["clusters"])
for key, name in NAMES.items():
    m(f"sharc{name}Micro", f"{s['designs'][key]['micro']:.3f}")
for key, name in (("cp_core-direct|micro", "Direct"), ("cp_core-steps|micro", "Steps"), ("cp_core-sc3|micro", "SC")):
    p = s["paired"][key]
    m(f"sharcCoreVs{name}Diff", f"{p['diff']:+.3f}")
    m(f"sharcCoreVs{name}Lo", f"{p['ci95'][0]:+.3f}")
    m(f"sharcCoreVs{name}Hi", f"{p['ci95'][1]:+.3f}")
m("sharcCostUSD", f"{s['cost']['total_ledger_usd']:.2f}")

OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {len(lines) - 1} macros to {OUT}")
