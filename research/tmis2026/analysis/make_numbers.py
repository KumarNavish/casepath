"""Write paper/results/numbers.tex: every number the paper reports, as a macro,
computed from the evidence files in this folder. Never edit numbers by hand."""
import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "paper" / "results" / "numbers.tex"
OUT.parent.mkdir(parents=True, exist_ok=True)
lines = ["% Generated by analysis/make_numbers.py from the evidence files. Do not edit."]


def m(name, value, fmt="{}"):
    lines.append(f"\\newcommand{{\\{name}}}{{{fmt.format(value)}}}")


def pct(x, d=1):
    return f"{100 * x:.{d}f}"


def load(name):
    p = HERE / name
    return json.loads(p.read_text()) if p.exists() else None


models = {"Terra": "gpt-6.1-terra", "Luna": "gpt-6-luna"}
for M, tag in models.items():
    r = load(f"results_{tag}.json")
    if not r:
        continue
    t = r.get("tenancy", {})
    names = {"Bone": "B1", "Bsc": "B1-SC3", "Btwo": "B2", "CPk": "CP-kleene", "CPkn": "CP-kleene-noverifier",
             "CPx": "CP-exact", "CPxn": "CP-exact-noverifier"}
    for short, key in names.items():
        v = t.get(key)
        if not v:
            continue
        p = f"ten{M}{short}"
        m(p + "Recall", pct(v["recall"])); m(p + "RecallLo", pct(v["recall_ci"][0])); m(p + "RecallHi", pct(v["recall_ci"][1]))
        m(p + "Unnec", pct(v["unnecessary_rate"])); m(p + "Defer", pct(v["deferral_rate"]))
        m(p + "DeferLo", pct(v["deferral_rate_ci"][0])); m(p + "DeferHi", pct(v["deferral_rate_ci"][1]))
        m(p + "Miss", pct(v["silent_miss_rate"])); m(p + "Holds", f"{v['holds_per_claim']:.1f}")
        m(p + "Unsafe", f"{v['unsafe_per_claim']:.2f}"); m(p + "Reqs", f"{v['requests_per_claim']:.1f}")
        m(p + "FamAcc", pct(v["family_accuracy"])); m(p + "ClaimDef", pct(v["claim_deferral"]))
        m(p + "FP", v["fp"]); m(p + "MissN", v["miss"]); m(p + "DeferN", v["defer"]); m(p + "TP", v["tp"]); m(p + "NR", v["nR"])
        if v.get("test_retest_jaccard") is not None:
            m(p + "Retest", f"{v['test_retest_jaccard']:.3f}"); m(p + "Ident", pct(v["claims_identical_across_runs"], 0))
    for i, c in enumerate(t.get("_contrasts", [])):
        m(f"ten{M}C{'ABCD'[i]}Diff", f"{c['diff']:+.3f}"); m(f"ten{M}C{'ABCD'[i]}P", f"{c['p_signflip']:.4f}".rstrip('0'))
    th = r.get("theft", {})
    tnames = {"D": "D", "R": "R", "Dsc": "D-SC3", "Rsc": "R-SC3", "CP": "CP", "CPn": "CP-noverifier", "CPall": "CP-allroutes"}
    for short, key in tnames.items():
        v = th.get(key)
        if not v:
            continue
        p = f"th{M}{short}"
        on = v["on"]
        m(p + "Fone", f"{on['f1']:.3f}"); m(p + "FoneLo", f"{on['f1_ci'][0]:.2f}"); m(p + "FoneHi", f"{on['f1_ci'][1]:.2f}")
        m(p + "Wrong", on["wrong"]); m(p + "WrongAdd", on["wrong_add"]); m(p + "WrongWd", on["wrong_withdraw"])
        m(p + "Missed", on["missed"]); m(p + "Correct", on["correct"]); m(p + "Exact", pct(on["exact_rate"], 0))
        m(p + "WrongPP", f"{on['wrong_per_pair']:.2f}"); m(p + "MissedPP", f"{on['missed_per_pair']:.2f}")
        m(p + "WrongPerRun", f"{on['wrong'] / 3:.1f}"); m(p + "MissedPerRun", f"{on['missed'] / 3:.1f}")
        m(p + "AgreedFone", f"{v['on_agreed_references']['f1']:.3f}")
        u = v["unresolved"]
        m(p + "Premature", pct(u["premature_rate"], 0)); m(p + "Stable", pct(u["stable_rate"], 0)); m(p + "Held", pct(u["held_rate"], 0))
        if v.get("test_retest_jaccard") is not None:
            m(p + "Retest", f"{v['test_retest_jaccard']:.3f}"); m(p + "Ident", pct(v["texts_identical_across_runs"], 0))
    for i, c in enumerate(th.get("_contrasts", [])):
        m(f"th{M}C{'ABCD'[i]}Diff", f"{c['diff_mean_over_conditions']:+.2f}"); m(f"th{M}C{'ABCD'[i]}P", f"{c['p_signflip']:.3f}")
    cost = r.get("costs", {})
    def per(keys, n):
        return sum(cost.get(k, {}).get("cost", 0) for k in keys) / n if n else 0
    calls = lambda k: cost.get(k, {}).get("calls", 0)
    if calls("tenancy|B1"):
        m(f"cost{M}TenBone", f"{1000 * per(['tenancy|B1'], calls('tenancy|B1')):.1f}")
        m(f"cost{M}TenCP", f"{1000 * per(['tenancy|CP-interpret', 'tenancy|CP-verify'], calls('tenancy|CP-interpret')):.1f}")
    if calls("tenancy|B2"):
        m(f"cost{M}TenBtwo", f"{1000 * per(['tenancy|B2'], calls('tenancy|B2')):.1f}")
    if calls("theft|R"):
        m(f"cost{M}ThR", f"{1000 * per(['theft|R'], calls('theft|R')):.1f}")
        m(f"cost{M}ThCP", f"{1000 * per(['theft|CP-interpret', 'theft|CP-verify'], calls('theft|CP-interpret')):.1f}")
    if calls("theft|D"):
        m(f"cost{M}ThD", f"{1000 * per(['theft|D'], calls('theft|D')):.1f}")
    lat = lambda k: cost.get(k, {}).get("latency", 0) / max(1, calls(k))
    if calls("tenancy|B1"):
        m(f"lat{M}TenBone", f"{lat('tenancy|B1'):.0f}"); m(f"lat{M}TenCP", f"{lat('tenancy|CP-interpret') + lat('tenancy|CP-verify'):.0f}")
    m(f"spend{M}", f"{sum(v['cost'] for v in cost.values()):.2f}")

# explanatory tenancy analyses (terra)
x = load("tenancy_extra_gpt-6.1-terra.json")
if x:
    d = x["deferral_causes"]
    total_def = d.get("routing_fact", 0) + d.get("claim_deferred", 0) + d.get("other_condition", 0)
    m("defRouting", d.get("routing_fact", 0)); m("defClaim", d.get("claim_deferred", 0)); m("defOther", d.get("other_condition", 0))
    m("defTotal", total_def); m("defRequired", d["required_total"])
    rp = x["routing_presumption"]
    m("presRecall", pct(rp["tp"] / rp["nR"])); m("presUnnec", pct(rp["fp"] / rp["nP"])); m("presDefer", pct(rp["defer"] / rp["nR"]))
    m("presMiss", pct(rp["miss"] / rp["nR"]))
    for k, v in x["citations"].items():
        m("cit" + {"B1": "Bone", "B2": "Btwo", "CP-proposal": "CPProp"}[k], v["citations"])
    ver = x["verifier"]
    m("verChecked", ver["checked"]); m("verRejected", ver["rejected"]); m("verRejTrue", ver.get("rejected_true", 0))
j = load("judgment_accuracy_gpt-6.1-terra.json")
if j:
    m("jaCorrect", j["interp | correct"]); m("jaFlipped", j["interp | flipped"]); m("jaUnres", j["interp | unresolved"])
    m("jaUnresFalse", j["interp | unresolved | truth_false"]); m("jaUnresTrue", j["interp | unresolved | truth_true"])
    m("jaTotal", j["interp | correct"] + j["interp | flipped"] + j["interp | unresolved"])
    m("jaRejCorrect", j.get("verifier_rejected | was_correct", 0)); m("jaRejWrong", j.get("verifier_rejected | was_flipped", 0))
rv = load("rule_verification.json")
if rv:
    res = rv["results"]
    m("rvRules", len(res)); m("rvFlagged", sum(1 for v in res.values() if v["result"] and v["result"]["verdict"] == "flag"))
    m("rvImplicated", len(rv["implicated"]))
    m("rvImplicatedFlagged", sum(1 for k in rv["implicated"] if res[k]["result"] and res[k]["result"]["verdict"] == "flag"))
s1 = load("../scicore/out_local/s1_propagation.json") if (HERE.parent / "scicore/out_local/s1_propagation.json").exists() else None
if s1:
    g = {(row["eps"], row["rho"]): row for row in s1}
    m("propClaims", s1[0]["claims"]); m("propRequired", s1[0]["required_total"])
    a = g[(0.1, 1.0)]
    m("propKleeneExtra", f"{100 * (a['kleene_deferred'] / a['exact_deferred'] - 1):.0f}")
    m("propClosedMiss", f"{a['closed_missed']:.1f}"); m("propEagerUnnec", f"{a['eager_unnecessary'] - g[(0.0, 1.0)]['eager_unnecessary']:.1f}")
    m("propExactDefer", f"{a['exact_deferred']:.1f}")
    b = g[(0.1, 0.0)]
    m("propFlipUnnec", f"{b['exact_unnecessary'] - g[(0.0, 0.0)]['exact_unnecessary']:.1f}"); m("propFlipMiss", f"{b['exact_missed']:.1f}")
s2 = load("../scicore/out_local/s2_scalability.json") if (HERE.parent / "scicore/out_local/s2_scalability.json").exists() else None
if s2:
    import statistics
    m("scaleHundredMs", f"{1000 * statistics.median(r['seconds'] for r in s2['evaluate'] if r['nodes'] == 100):.0f}")
    m("scaleTenMs", f"{1000 * statistics.median(r['seconds'] for r in s2['evaluate'] if r['nodes'] == 10):.1f}")
    ex = {r["open_flags"]: r["seconds"] for r in s2["exact"]}
    m("scaleExactTen", f"{ex[10]:.0f}"); m("scaleExactFour", f"{1000 * ex[4]:.0f}")
ec = load("error_causes.json")
if ec:
    m("ecWrongFaulty", ec["theft_cp_wrong_by_faulty_rules"]); m("ecMissedFaulty", ec["theft_cp_missed_on_both_lists_by_faulty_rules"])
    m("ecTenUnnecFlip", ec["tenancy_cpexact_unnecessary_from_flipped_verdicts"]); m("ecTenMissSuff", ec["tenancy_cpexact_missed_judged_sufficient_ref_insufficient"])
pt = load("primary_tests.json")
if pt:
    for M, tag in models.items():
        for i, row in enumerate(pt.get(tag, [])):
            h = "HOneHTwoHThreeHFourHFive"
            name = ["HOne", "HTwo", "HThree", "HFour", "HFive"][i]
            ph = row["p_holm"]
            m(f"pt{M}{name}", ("<0.001" if ph < 0.001 else f"{ph:.3f}"))
            if "retest_diff" in row:
                m(f"pt{M}{name}Diff", f"{row['retest_diff']:+.2f}")
OUT.write_text("\n".join(lines) + "\n")
print(f"wrote {len(lines) - 1} macros to {OUT}")
