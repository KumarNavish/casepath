lines = ["% Generated by analysis/make_numbers.py from the evidence files. Do not edit."]


def m(name, value, fmt="{}"):
    lines.append(f"\\newcommand{{\\{name}}}{{{fmt.format(value)}}}")


def pct(x, d=1):
    return f"{100 * x:.{d}f}"


def load(name):
    p = HERE / name
    return json.loads(p.read_text()) if p.exists() else None


def fmtp(x):
    return "<0.001" if x < 0.001 else f"{x:.3f}"


